/* ============================================================================
 * 文件: login.h
 * 说明: 账号密码登录模块
 *      - 启动时弹出登录框, 输入账号 + 密码
 *      - 内置默认账户 123 / 123, 密码可被运行时改写
 *      - 密码长度 1..12, 账号长度 1..16
 *      - 校验通过返回 0, 失败提示重试, 累计 3 次错误返回 -1
 *      - 3 次错误后允许跳过 (skip), 跳过也返回 0 (供调试)
 *      - login_set_password() 供主界面"设置密码"入口调用, 改内存中的密码
 * ==========================================================================*/
#ifndef LOGIN_H
#define LOGIN_H

/* 显示登录界面
 *  - 阻塞直到登录成功或用户选择"跳过"
 *  返回: 0 登录成功/跳过, -1 异常退出
 */
int  login_run(void);

/* 主界面"设置密码":
 *  1) 验证当前密码 (默认 123)
 *  2) 输入新密码, 再次输入确认
 *  3) 两次一致则更新内存中的密码
 *  返回: 0 修改成功, -1 用户取消或验证失败
 *
 *  注意: 修改的密码只保存在内存, 重启后回到默认 123.
 *        如需持久化, 可在本函数末尾写入 /etc/rk3566_passwd 等.
 */
int  login_set_password(void);

#endif /* LOGIN_H */
