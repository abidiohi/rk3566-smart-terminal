/* ============================================================================
 * 文件: album.h
 * 说明: 相册浏览模块
 *      - 扫描指定目录, 加载所有 24 位 BMP 文件作为图片列表
 *      - 全屏显示当前图片 (居中等比缩放)
 *      - 支持: 下一张 / 上一张 / 退出
 *        * 点击屏幕左半区 → 上一张
 *        * 点击屏幕右半区 → 下一张
 *        * 点击屏幕顶部"返回"按钮 → 退出
 *        * 滑动方向 (左/右) 等同于点击右/左半区
 *      - 无图片时显示提示信息
 * ==========================================================================*/
#ifndef ALBUM_H
#define ALBUM_H

/* 默认相册目录 */
#define ALBUM_DEFAULT_DIR    "/usr/share/album"

/* 启动相册浏览
 *  - dir: 相册图片所在目录, NULL 时使用 ALBUM_DEFAULT_DIR
 *  返回: 0 正常退出, -1 错误(目录不存在, 初始化失败等)
 */
int  album_run(const char *dir);

#endif /* ALBUM_H */
